import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';

test('additive FRC links preserve legacy rows and enforce session/context in isolated PostgreSQL',async()=>{
 const modulePath=process.env.PDI_TEST_PGLITE_MODULE;
 assert.ok(modulePath,'PDI_TEST_PGLITE_MODULE must point to the existing isolated PostgreSQL runtime');
 const {PGlite}=await import(pathToFileURL(modulePath).href);const db=new PGlite();
 const admin='10000000-0000-0000-0000-000000000001',scout='10000000-0000-0000-0000-000000000002',other='10000000-0000-0000-0000-000000000003';
 const season='20000000-0000-0000-0000-000000000001',event='30000000-0000-0000-0000-000000000001',team='40000000-0000-0000-0000-000000000001';
 try{
 await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE SCHEMA auth;
 CREATE TABLE auth.users(id uuid PRIMARY KEY);
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('test.actor',true),'')::uuid $$;
 CREATE FUNCTION public.is_admin() RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT auth.uid()='${admin}'::uuid $$;
 CREATE FUNCTION public.portal_has_modality(text) RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT coalesce(current_setting('test.frc',true),'')='yes' $$;
 CREATE FUNCTION public.portal_can_edit() RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT coalesce(current_setting('test.edit',true),'')='yes' $$;
 GRANT USAGE ON SCHEMA auth TO authenticated; GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated;
 CREATE TABLE public.seasons(id uuid PRIMARY KEY,program text);
 CREATE TABLE public.tournament_configs(id uuid PRIMARY KEY,category text,tournament_name text);
 CREATE TABLE public.teams(id uuid PRIMARY KEY,number text UNIQUE,program text);
 CREATE TABLE public.frc_scouts(id uuid PRIMARY KEY,team_number text,match_number text,scout_name text,notes text);
 INSERT INTO auth.users VALUES('${admin}'),('${scout}'),('${other}');
 INSERT INTO seasons VALUES('${season}','FRC');
 INSERT INTO teams VALUES('${team}','10343','FRC');
 INSERT INTO tournament_configs VALUES('${event}','FRC','Regional 1');
 INSERT INTO frc_scouts VALUES('50000000-0000-0000-0000-000000000000','10343','Q0','legacy','preserve');
 GRANT SELECT,INSERT,UPDATE,DELETE ON seasons,teams,tournament_configs,frc_scouts TO authenticated;
 SELECT set_config('test.actor','${admin}',false),set_config('test.frc','yes',false),set_config('test.edit','yes',false);`);
 await db.exec(await readFile(new URL('../supabase/migrations/20261125_frc_scouting_links.sql',import.meta.url),'utf8'));
 assert.equal((await db.query('SELECT notes FROM frc_scouts')).rows[0].notes,'preserve');
 assert.equal((await db.query('SELECT scouting_user_id FROM frc_scouts')).rows[0].scouting_user_id,null);
 await db.exec(`SET ROLE authenticated; UPDATE tournament_configs SET scouting_season_id='${season}' WHERE id='${event}'; INSERT INTO frc_scouting_event_teams VALUES('${event}','${team}');`);
 await db.exec(`SELECT set_config('test.actor','${scout}',false);`);
 const insert=(id,extra='')=>`INSERT INTO frc_scouts(id,team_number,match_number,scouting_season_id,scouting_event_id${extra?',scouting_user_id':''}) VALUES('50000000-0000-0000-0000-${id}','10343','Q1','${season}','${event}'${extra?`,'${extra}'`:''})`;
 await assert.rejects(db.exec(insert('000000000001',other)),/FRC_AUTHOR_MISMATCH/);
 await db.exec(insert('000000000001'));
 assert.equal((await db.query("SELECT scouting_user_id FROM frc_scouts WHERE match_number='Q1'")).rows[0].scouting_user_id,scout);
 await db.exec(`SELECT set_config('test.actor','${other}',false);`);
 await assert.rejects(db.exec("UPDATE frc_scouts SET notes='forged' WHERE match_number='Q1'"),/FRC_OWNER_REQUIRED/);
 await assert.rejects(db.exec("UPDATE frc_scouts SET scouting_event_id=null,scouting_season_id=null,scouting_user_id=null WHERE match_number='Q1'"),/FRC_CONTEXT_IMMUTABLE/);
 await db.exec(`SELECT set_config('test.edit','no',false);`);
 await assert.rejects(db.exec(insert('000000000002')),/FRC_WRITE_DENIED/);
 await db.exec(`SELECT set_config('test.edit','yes',false),set_config('test.frc','no',false);`);
 await assert.rejects(db.exec(insert('000000000002')),/FRC_WRITE_DENIED/);
 assert.equal((await db.query('SELECT * FROM frc_scouting_event_teams')).rows.length,0);
 await db.exec(`SELECT set_config('test.actor','${admin}',false),set_config('test.frc','yes',false);`);
 await assert.rejects(db.exec(`UPDATE tournament_configs SET scouting_season_id=null WHERE id='${event}'`),/FRC_EVENT_ALREADY_LINKED/);
 await assert.rejects(db.exec(`UPDATE teams SET program='FTC' WHERE id='${team}'`),/FRC_TEAM_IN_USE/);
 await assert.rejects(db.exec(`DELETE FROM frc_scouting_event_teams WHERE event_id='${event}'`),/FRC_PARTICIPATION_IN_USE/);
 await db.exec(`UPDATE tournament_configs SET tournament_name='Regional 2026' WHERE id='${event}'`);
 assert.equal((await db.query("SELECT scouting_event_id FROM frc_scouts WHERE match_number='Q1'")).rows[0].scouting_event_id,event);
 await assert.rejects(db.exec(insert('000000000003').replace("'10343'","'9164'")),/FRC_TEAM_NOT_IN_EVENT/);
 await assert.rejects(db.exec(insert('000000000003').replace(`'${season}'`,`'20000000-0000-0000-0000-000000000099'`)),/FRC_EVENT_SCOPE_MISMATCH/);
 await assert.rejects(db.exec(`UPDATE seasons SET program='FTC' WHERE id='${season}'`),/FRC_SEASON_IN_USE/);
 await db.exec('RESET ROLE');
 await db.exec(await readFile(new URL('../supabase/rollbacks/20261125_frc_scouting_links.sql',import.meta.url),'utf8'));
 assert.equal((await db.query('SELECT count(*)::int AS n FROM frc_scouts')).rows[0].n,2);
 await db.exec('SET ROLE authenticated');
 await assert.rejects(db.exec(insert('000000000004')),/FRC_SCOUTING_SUSPENDED/);
 await db.exec("UPDATE frc_scouts SET notes='legacy still editable' WHERE match_number='Q0'");
 }finally{await db.close();}
});
