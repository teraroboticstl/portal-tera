test('modality display and private media use verified permissions, not the questionnaire/profile program',()=>{
 const snapshot={actor:'a',modalities:['FTC','OBR']};
 assert.equal(canDisplayModality('FTC',snapshot,'a'),true);
 assert.equal(canDisplayModality('OBR Resgate Nível 1',snapshot,'a'),true);
 assert.equal(canDisplayModality('FRC',snapshot,'a'),false);
 assert.equal(canDisplayModality('FTC',snapshot,'b'),false);
 assert.equal(canDisplayModality('FTC',null,'a'),false);
 assert.equal(canDisplayModality('FRC',{...snapshot,all_modalities:true},'a'),true);
 const profile={portal_internal:true,modality_access_enabled:true,allowed_modalities:['FTC'],program:'FRC'};
 assert.equal(canUseProgram(profile,'FTC'),true);assert.equal(canUseProgram(profile,'FRC'),false);
 assert.equal(canUseProgram(profile,'Geral'),true);assert.equal(canUseProgram(profile,'unknown'),false);
 assert.equal(canUseProgram({...profile,portal_internal:false},'FTC'),false);
 assert.equal(canUseProgram({...profile,all_modalities:true},'FRC'),true);
});
